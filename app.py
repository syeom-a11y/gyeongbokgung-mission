def get_existing_image_path(base_name):
    for ext in [".png", ".PNG", ".jpg", ".JPG", ".jpeg", ".JPEG"]:
        full_path = f"{base_name}{ext}"
        if os.path.exists(full_path):
            return full_path
    return None

